#!/usr/bin/env python3
"""Generate held-out manuscript tables and a result audit from frozen artifacts."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESULTS = REPO_ROOT / "reports" / "publication" / "conference"
DEFAULT_CHARACTERIZATION = (
    REPO_ROOT / "research" / "results" / "heldout_characterization.json"
)
DEFAULT_OUTPUT = REPO_ROOT / "paper" / "tables"

ABLATIONS = (
    ("Full system", "safemap_deterministic"),
    ("Without pointer roles", "safemap_without_pointer_roles"),
    ("Without safe signatures", "safemap_without_safe_signatures"),
    ("Without dependency grouping", "safemap_without_dependency_grouping"),
    ("Without idiom plans", "safemap_without_idiom_plans"),
    ("Without validation feedback", "safemap_without_validation_feedback"),
)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _display(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _number(row: dict[str, str], field: str) -> int:
    value = row.get(field, "").strip()
    return int(float(value)) if value else 0


def _sum(rows: list[dict[str, str]], field: str) -> int:
    return sum(_number(row, field) for row in rows)


def _mode(rows: list[dict[str, str]], name: str) -> list[dict[str, str]]:
    selected = [row for row in rows if row["mode"] == name]
    if len(selected) != 3:
        raise ValueError(f"Expected three project rows for {name}, found {len(selected)}")
    return selected


def _write_corpus(path: Path, characterization: dict[str, Any]) -> None:
    lines = [
        "% Generated by scripts/generate_heldout_manuscript_tables.py; do not edit.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Frozen held-out corpus characterization.}",
        r"\label{tab:heldout-corpus}",
        r"\resizebox{\columnwidth}{!}{%",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        "Project & C LOC & Functions & Parameters & Pointer params. & Complexity \\\\",
        r"\midrule",
    ]
    for item in characterization["project_distribution"]:
        lines.append(
            f"{item['project']} & {item['source_loc']} & {item['functions']} & "
            f"{item['parameters']} & {item['pointer_parameters']} & "
            f"{item['complexity_total']} " + r"\\"
        )
    lines.extend([
        r"\midrule",
        f"Total & {characterization['source_loc']} & {characterization['function_count']} & "
        f"{sum(item['parameters'] for item in characterization['project_distribution'])} & "
        f"{sum(item['pointer_parameters'] for item in characterization['project_distribution'])} & "
        f"{sum(item['complexity_total'] for item in characterization['project_distribution'])} " + r"\\",
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
        "",
    ])
    path.write_text("\n".join(lines), encoding="utf-8")


def _write_safemap_outcome(path: Path, rows: list[dict[str, str]]) -> dict[str, int]:
    values = {
        "translation_units": _sum(rows, "total_units"),
        "candidate_safe": _sum(rows, "candidate_safe_units"),
        "supported": _sum(rows, "synthesis_supported_units"),
        "generated": _sum(rows, "generated_units"),
        "compiled": _sum(rows, "compile_success_units"),
        "policy_safe": _sum(rows, "policy_safe_units"),
        "behavioral": _sum(rows, "behaviorally_validated_units"),
    }
    lines = [
        "% Generated by scripts/generate_heldout_manuscript_tables.py; do not edit.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Held-out SafeMAP outcome cascade. The 146 functions form 142",
        r"dependency-grouped translation units.}",
        r"\label{tab:heldout-cascade}",
        r"\begin{tabular}{lr}",
        r"\toprule",
        "Stage & Units \\\\",
        r"\midrule",
        f"Retained translation units & {values['translation_units']} " + r"\\",
        f"Candidate-safe & {values['candidate_safe']} " + r"\\",
        f"Implemented support & {values['supported']} " + r"\\",
        f"Generated & {values['generated']} " + r"\\",
        f"Compiled & {values['compiled']} " + r"\\",
        f"Policy-safe & {values['policy_safe']} " + r"\\",
        f"Behaviorally validated & {values['behavioral']} " + r"\\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return values


def _project_for_log(path: Path) -> str:
    project_path = path.parents[1] / "project.json"
    return str(json.loads(project_path.read_text(encoding="utf-8"))["project_name"])


def _baseline_records(results: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    c2rust_logs = sorted(results.glob("raw/non-llm/c2rust_only/**/logs/c2rust.json"))
    llm_logs = sorted(results.glob("raw/llm/llm_only/**/logs/direct_llm_call.json"))
    if len(c2rust_logs) != 3 or len(llm_logs) != 3:
        raise ValueError("Expected exactly three C2Rust logs and three LLM call logs")
    c2rust = []
    for path in c2rust_logs:
        record = json.loads(path.read_text(encoding="utf-8"))
        c2rust.append({
            "project": _project_for_log(path),
            "status": record.get("status", "unknown"),
            "reason": record.get("reason") or record.get("error") or "",
        })
    llm = []
    for path in llm_logs:
        record = json.loads(path.read_text(encoding="utf-8"))
        llm.append({
            "project": _project_for_log(path),
            "status": record.get("status", "unknown"),
            "response_model": record.get("response_model", ""),
            "input_tokens": int(record.get("input_tokens") or 0),
            "output_tokens": int(record.get("output_tokens") or 0),
            "failure": record.get("failure") or record.get("error") or "",
        })
    return {
        "attempts": len(c2rust),
        "outputs": sum(item.get("status") == "passed" for item in c2rust),
        "status_counts": dict(sorted(Counter(item.get("status", "unknown") for item in c2rust).items())),
        "projects": c2rust,
    }, {
        "attempts": len(llm),
        "outputs": sum(item.get("status") == "completed" for item in llm),
        "status_counts": dict(sorted(Counter(item.get("status", "unknown") for item in llm).items())),
        "input_tokens": sum(int(item.get("input_tokens") or 0) for item in llm),
        "output_tokens": sum(int(item.get("output_tokens") or 0) for item in llm),
        "projects": llm,
    }


def _write_baselines(
    path: Path,
    c2rust: dict[str, Any],
    llm: dict[str, Any],
) -> None:
    lines = [
        "% Generated by scripts/generate_heldout_manuscript_tables.py; do not edit.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Held-out project-level baseline outcomes under the shared policy.}",
        r"\label{tab:heldout-baselines}",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        "Lane & Attempts & Outputs & Compiled & Accepted \\\\",
        r"\midrule",
        f"Raw C2Rust & {c2rust['attempts']} & {c2rust['outputs']} & 0 & 0 " + r"\\",
        f"Direct Gemini & {llm['attempts']} & {llm['outputs']} & 0 & 0 " + r"\\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def _write_ablations(path: Path, rows: list[dict[str, str]]) -> list[dict[str, int | str]]:
    values: list[dict[str, int | str]] = []
    for label, mode in ABLATIONS:
        selected = _mode(rows, mode)
        values.append({
            "label": label,
            "mode": mode,
            "units": _sum(selected, "total_units"),
            "candidate": _sum(selected, "candidate_safe_units"),
            "supported": _sum(selected, "synthesis_supported_units"),
            "generated": _sum(selected, "generated_units"),
            "compiled": _sum(selected, "compile_success_units"),
            "accepted": _sum(selected, "behaviorally_validated_units"),
        })
    lines = [
        "% Generated by scripts/generate_heldout_manuscript_tables.py; do not edit.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Held-out component ablations. ``Supp.'' is implemented support.}",
        r"\label{tab:heldout-ablations}",
        r"\resizebox{\columnwidth}{!}{%",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        "Configuration & Candidate & Supp. & Generated & Accepted \\\\",
        r"\midrule",
    ]
    for item in values:
        lines.append(
            f"{item['label']} & {item['candidate']} & {item['supported']} & "
            f"{item['generated']} & {item['accepted']} " + r"\\"
        )
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
        "",
    ])
    path.write_text("\n".join(lines), encoding="utf-8")
    return values


def generate(results: Path, characterization_path: Path, output: Path) -> dict[str, Any]:
    csv_path = results / "benchmark_results.csv"
    reproduction_path = results / "reproduction_manifest.json"
    required = (csv_path, reproduction_path, characterization_path)
    missing = [path for path in required if not path.is_file()]
    if missing:
        raise FileNotFoundError("Missing held-out input(s): " + ", ".join(map(str, missing)))
    reproduction = json.loads(reproduction_path.read_text(encoding="utf-8"))
    rows = _read_csv(csv_path)
    if len(rows) != 24:
        raise ValueError(f"Expected 24 held-out project/mode rows, found {len(rows)}")
    commits = {row["git_commit"] for row in rows}
    if commits != {reproduction["freeze_git_commit"]}:
        raise ValueError("Held-out CSV commit does not match the freeze manifest")
    characterization = json.loads(characterization_path.read_text(encoding="utf-8"))
    if characterization.get("function_count") != 146:
        raise ValueError("Frozen characterization no longer has 146 functions")

    output.mkdir(parents=True, exist_ok=True)
    corpus_path = output / "heldout_corpus.tex"
    cascade_path = output / "heldout_cascade.tex"
    baseline_path = output / "heldout_baselines.tex"
    ablation_path = output / "heldout_ablations.tex"
    _write_corpus(corpus_path, characterization)
    safemap = _write_safemap_outcome(
        cascade_path, _mode(rows, "safemap_deterministic")
    )
    c2rust, llm = _baseline_records(results)
    _write_baselines(baseline_path, c2rust, llm)
    ablations = _write_ablations(ablation_path, rows)

    outputs = (corpus_path, cascade_path, baseline_path, ablation_path)
    manifest = {
        "schema_version": "safemap.heldout_manuscript_tables.v1",
        "freeze_git_commit": reproduction["freeze_git_commit"],
        "inputs": {
            _display(path): _sha256(path) for path in required
        },
        "safemap_outcome": safemap,
        "c2rust_baseline": c2rust,
        "llm_baseline": llm,
        "ablations": ablations,
        "human_review_status": "awaiting_two_independent_reviews_and_adjudication",
        "outputs": {_display(path): _sha256(path) for path in outputs},
    }
    manifest_path = output / "heldout_manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    audit = [
        "# Held-out result claim audit",
        "",
        "Generated by `scripts/generate_heldout_manuscript_tables.py`; do not edit by hand.",
        "",
        f"- Frozen implementation: `{manifest['freeze_git_commit']}`",
        f"- Retained source functions: `{characterization['function_count']}`",
        f"- Dependency-grouped translation units: `{safemap['translation_units']}`",
        f"- SafeMAP cascade: `{safemap['candidate_safe']}` candidate, "
        f"`{safemap['supported']}` supported, `{safemap['generated']}` generated, "
        f"`{safemap['compiled']}` compiled, `{safemap['policy_safe']}` policy-safe, "
        f"`{safemap['behavioral']}` behaviorally validated.",
        f"- Raw C2Rust: `{c2rust['attempts']}` invocations, `{c2rust['outputs']}` outputs, "
        "`0` accepted. All three transpilation attempts failed and remain in the denominator.",
        f"- Direct Gemini: `{llm['attempts']}` API requests, `{llm['outputs']}` retained output, "
        f"`0` compiled and `0` accepted; raw logs record `{llm['input_tokens']}` input and "
        f"`{llm['output_tokens']}` output tokens.",
        "- Human eligibility precision, recall, agreement, and adjudication are pending and must not be inferred.",
        "",
        "Every prompt, response, plan, decision, validation record, seed, environment record, and tool-version file is hashed in `reports/publication/conference/reproduction_manifest.json`.",
        "",
    ]
    (output.parent / "HELDOUT_RESULT_AUDIT.md").write_text(
        "\n".join(audit), encoding="utf-8"
    )
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument(
        "--characterization", type=Path, default=DEFAULT_CHARACTERIZATION
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    result = generate(
        args.results.resolve(), args.characterization.resolve(), args.output.resolve()
    )
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
